  /* uzun metinler için son çare zinciri: istenen dil -> en -> tr */
  function t(lang, key) {
    const d = dict[lang];
    if (d && Object.prototype.hasOwnProperty.call(d, key)) return d[key];
    if (dict.en && Object.prototype.hasOwnProperty.call(dict.en, key)) return dict.en[key];
    if (dict.tr && Object.prototype.hasOwnProperty.call(dict.tr, key)) return dict.tr[key];
    return key;
  }

  function template(str, vars) {
    return String(str).replace(/\{(\w+)\}/g, (_m, name) =>
      Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`,
    );
  }

  function apply(lang, vars = {}) {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const raw = t(lang, el.dataset.i18n);
      el.textContent = template(raw, vars);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      const raw = t(lang, el.dataset.i18nPh);
      el.placeholder = template(raw, vars);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const raw = t(lang, el.dataset.i18nTitle);
      el.title = template(raw, vars);
      el.setAttribute('aria-label', template(raw, vars));
    });
  }

  window.ZelixI18N = {
    LANGS,
    codes: LANGS.map(([code]) => code),
    nativeName: (code) => (LANGS.find(([c]) => c === code) || [code, null])[1],
    dict,
    t,
    template,
    apply,
  };
